    expect(page.get_by_text("No project connected yet")).to_be_visible()
    expect(page.get_by_role("region", name="Projects")).to_have_count(0)
    assert page.request.get("/devflow/api/projects").json() == {"projects": []}
    page.reload()
    expect(page.get_by_text("No project connected yet")).to_be_visible()


